import { chromium } from "playwright";
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await p.goto("http://localhost:5173/", { waitUntil: "networkidle" });
await p.waitForTimeout(1200);
await p.evaluate(() => document.querySelector("[data-rv-section='features']")?.scrollIntoView({ block: "start" }));
await p.waitForTimeout(1800);
const cap = await p.$eval("[data-rv-section='features'] figcaption", e => e.textContent.trim());
const pathLen = await p.$$eval("[data-rv-section='features'] svg path", els => els.length);
console.log("figcaption:", JSON.stringify(cap.slice(0, 80)));
console.log("svg paths drawn in section:", pathLen);
await (await p.$("[data-rv-section='features']")).screenshot({ path: process.argv[2] + "/features-live.png" });
await b.close();
